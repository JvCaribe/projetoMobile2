CREATE OR REPLACE VIEW contas_ativas AS
SELECT * FROM contas WHERE excluido_em IS NULL;

CREATE OR REPLACE VIEW transacoes_ativas AS
SELECT * FROM transacoes WHERE excluido_em IS NULL;
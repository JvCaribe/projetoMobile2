ALTER TABLE usuarios   ADD COLUMN IF NOT EXISTS excluido_em TIMESTAMP NULL;
ALTER TABLE contas     ADD COLUMN IF NOT EXISTS excluido_em TIMESTAMP NULL;
ALTER TABLE transacoes ADD COLUMN IF NOT EXISTS excluido_em TIMESTAMP NULL;

CREATE OR REPLACE VIEW usuarios_ativos AS
